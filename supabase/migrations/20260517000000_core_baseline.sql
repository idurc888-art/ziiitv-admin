-- This migration intentionally precedes every historical incremental migration.
-- It makes a brand-new Supabase project reproducible without SQL Editor steps.

create extension if not exists pgcrypto;
create extension if not exists "uuid-ossp";

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  role text not null default 'user' check (role in ('user', 'admin')),
  m3u_url text,
  last_processed timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.canonical_titles (
  id text primary key,
  slug text not null unique,
  title text not null,
  alt_titles text[] not null default '{}',
  type text not null check (type in ('movie', 'series')),
  streaming text not null default 'outros',
  match_hints text[] not null default '{}',
  genres text[] not null default '{}',
  tmdb_id integer,
  year text,
  rating numeric(3,1),
  overview text,
  poster text,
  backdrop text,
  director text,
  age_rating text,
  duration integer,
  trailer_url text,
  priority boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.homes (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  description text,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists homes_single_active_idx
  on public.homes (is_active) where is_active;

create table if not exists public.playlists (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  url_original text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'ready', 'error')),
  channel_count integer not null default 0 check (channel_count >= 0),
  error_message text,
  processed_at timestamptz,
  presentation_mode text not null default 'auto' check (presentation_mode in ('auto', 'curated')),
  last_synced_at timestamptz,
  content_count integer not null default 0 check (content_count >= 0),
  home_id uuid references public.homes(id) on delete set null,
  content_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pairing_codes (
  code text primary key check (code ~ '^ZIII-[A-Z2-9]{4}$'),
  user_id uuid not null references public.users(id) on delete cascade,
  playlist_id uuid references public.playlists(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  last_used_at timestamptz
);

create table if not exists public.channels (
  id uuid primary key default gen_random_uuid(),
  playlist_id uuid not null references public.playlists(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  name text not null,
  streams jsonb not null default '[]'::jsonb check (jsonb_typeof(streams) = 'array'),
  group_name text,
  logo_url text,
  canonical_id text references public.canonical_titles(id) on delete set null,
  streaming text,
  content_type text check (content_type is null or content_type in ('live', 'movie', 'series', 'show', 'standup')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.watch_history (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  device_id text,
  channel_id uuid references public.channels(id) on delete set null,
  canonical_id text references public.canonical_titles(id) on delete set null,
  channel_name text not null,
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  progress_pct integer not null default 0 check (progress_pct between 0 and 100),
  watched_at timestamptz not null default now()
);

create table if not exists public.watch_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete set null,
  device_id text,
  channel_id uuid references public.channels(id) on delete set null,
  canonical_id text references public.canonical_titles(id) on delete set null,
  event_type text not null default 'play',
  position_seconds integer not null default 0 check (position_seconds >= 0),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.home_sections (
  id uuid primary key default gen_random_uuid(),
  home_id uuid not null references public.homes(id) on delete cascade,
  title text not null,
  subtitle text,
  type text not null,
  source text,
  sort_order integer not null default 0,
