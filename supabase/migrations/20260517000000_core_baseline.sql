create or replace function public.update_updated_at_column()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.users (id, email, role)
  values (new.id, coalesce(new.email, new.id::text || '@invalid.local'), 'user')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.users
    where id = auth.uid() and role = 'admin'
  );
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

do $$
declare table_name text;
begin
  foreach table_name in array array['users', 'playlists', 'homes', 'home_sections', 'enrich_jobs', 'tv_sessions'] loop
    execute format('drop trigger if exists %I on public.%I', 'touch_' || table_name || '_updated_at', table_name);
    execute format('create trigger %I before update on public.%I for each row execute function public.update_updated_at_column()', 'touch_' || table_name || '_updated_at', table_name);
  end loop;
end $$;

create or replace function public.sync_linked_pair_token()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'linked' and old.status is distinct from 'linked' then
    insert into public.tv_sessions (
      device_id, device_name, device_model, playlist_url, playlist_type,
      xtream_host, xtream_user, xtream_pass, user_id, last_seen_at
    ) values (
      new.device_id, new.device_name, new.device_model, new.playlist_url, new.playlist_type,
      new.xtream_host, new.xtream_user, new.xtream_pass, new.user_id, now()
    )
    on conflict (device_id) do update set
      device_name = excluded.device_name,
      device_model = excluded.device_model,
      playlist_url = excluded.playlist_url,
      playlist_type = excluded.playlist_type,
      xtream_host = excluded.xtream_host,
      xtream_user = excluded.xtream_user,
      xtream_pass = excluded.xtream_pass,
      user_id = excluded.user_id,
      last_seen_at = now();
  end if;
  return new;
end;
$$;

