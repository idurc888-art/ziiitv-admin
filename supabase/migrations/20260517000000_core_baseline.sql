create table if not exists public.pair_tokens (
  id uuid primary key default gen_random_uuid(),
  token text not null unique default upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 8)),
  device_id text not null,
  device_name text,
  device_model text,
  status text not null default 'pending' check (status in ('pending', 'linked', 'expired')),
  playlist_url text,
  playlist_type text check (playlist_type is null or playlist_type in ('m3u', 'xtream')),
  xtream_host text,
  xtream_user text,
  xtream_pass text,
  user_id uuid references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '15 minutes'),
  linked_at timestamptz
);

